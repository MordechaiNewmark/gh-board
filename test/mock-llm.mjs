// A scripted stand-in for an LLM API, for tests. It speaks two wire protocols:
//   OpenAI chat completions (streaming, with tool_calls):  POST /v1/chat/completions, GET /v1/models
//                                                          (/nokey/v1/... is the same without auth, like Ollama)
//   Gemini generateContent (SSE, with functionCall parts): POST /v1beta/models/<m>:streamGenerateContent, GET /v1beta/models
// The "model" follows a script picked by a [[script:NAME]] marker in the latest user message; the step is
// the number of model turns since that message. Every request is recorded in `log` for assertions.
import http from 'node:http';

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** script(step, { repo, results }) -> { text?, calls?: [{ name, args | rawArgs }], status?, error?, slow? } */
export const SCRIPTS = {
  full: (step, { repo }) => [
    { text: 'I will sync the repo first.', calls: [{ name: 'sync_repo', args: { repo } }] },
    { calls: [{ name: 'list_issues', args: { repo, state: 'open' } }, { name: 'grep', args: { pattern: 'function|import|def ', max_results: 5 } }] },
    { calls: [{ name: 'glob', args: { pattern: '*.md' } }, { name: 'read_file_local', args: { path: 'README.md', limit: 12 } }] },
    { text: 'Now I will try to leave the checkout.', calls: [
      { name: 'read_file_local', args: { path: '../../server.mjs' } },
      { name: 'read_file_local', args: { path: '.git/config' } },
      { name: 'grep', args: { pattern: 'token', path: '../..' } },
      { name: 'glob', args: { pattern: '../*' } },
      { name: 'read_file_local', args: { path: 'C:/Windows/win.ini' } },
    ] },
    { text: '## Findings\n\nThe repo was explored. Proposed backlog follows.', calls: [{ name: 'create_issues', args: { repo, issues: [{ title: 'Epic: mock backlog', body: '## Goal\nMock epic body.', labels: ['enhancement'], children: [{ title: 'Mock child issue', body: '## Context\nMock child body.' }] }] } }] },
    { calls: [{ name: 'generate_file', args: { filename: 'mock-report.md', content: '# Mock report\n\nGenerated by the scripted model.\n' } }] },
    { text: 'Done. The write was blocked or rejected, so nothing was created. The report is attached above.' },
  ][step],
  write: (step, { repo }) => [
    { text: 'Creating the issue.', calls: [{ name: 'create_issue', args: { repo: repo || 'o/r', title: 'Mock issue' } }] },
    { text: 'Finished after the write step.' },
  ][step],
  retrywrite: (step, { repo }) => (step < 3 ? { calls: [{ name: 'create_issue', args: { repo: repo || 'o/r', title: 'Mock issue' } }] } : { text: 'I will stop retrying.' }),
  hello: () => ({ text: 'Hello from the mock model. No tools needed.' }),
  badjson: (step) => [{ calls: [{ name: 'list_issues', rawArgs: '{"repo": "o/r", ' }] }, { text: 'Recovered after the bad arguments.' }][step],
  unknown: (step) => [{ calls: [{ name: 'run_shell', args: { cmd: 'whoami' } }] }, { text: 'No shell here, understood.' }][step],
  loopfail: () => ({ calls: [{ name: 'list_issues', args: { repo: 'not a repo' } }] }),
  empty: () => ({ text: '' }),
  slow: () => ({ slow: true }),
  notools: () => ({ status: 400, error: 'registry.ollama.ai/library/tinymodel:latest does not support tools' }),
  ratelimit: () => ({ status: 429, error: 'You exceeded your current quota, please check your plan and billing details.' }),
  boom: () => ({ status: 500, error: 'upstream exploded' }),
};

const marker = (text) => /\[\[script:(\w+)\]\]/.exec(String(text || ''))?.[1];
const repoOf = (system) => (/Current repo: ([\w.-]+\/[\w.-]+)/.exec(String(system || ''))?.[1] || '').replace(/\.$/, '');

export function startMock({ key = '', port = 0 } = {}) {
  const log = [];
  let n = 0;
  const server = http.createServer(async (req, res) => {
    const url = new URL(req.url, 'http://mock');
    const chunks = []; for await (const c of req) chunks.push(c);
    let body = null; try { body = JSON.parse(Buffer.concat(chunks).toString('utf8') || 'null'); } catch {}
    const noKey = url.pathname.startsWith('/nokey/');
    const path = url.pathname.replace(/^\/nokey/, '');
    const given = (req.headers.authorization || '').replace(/^Bearer /, '') || req.headers['x-goog-api-key'] || '';
    const entry = { n: ++n, method: req.method, path, auth: given ? (given === key ? 'ok' : 'bad') : 'none', keyInUrl: url.search.includes('key='), body, aborted: false };
    log.push(entry);
    res.on('close', () => { if (!res.writableEnded) entry.aborted = true; });
    const json = (code, data) => { res.writeHead(code, { 'Content-Type': 'application/json' }); res.end(JSON.stringify(data)); };

    // A wrong key is echoed back in the error, the way some providers do, to prove the app scrubs it.
    if (!noKey && given !== key) return json(401, { error: { message: `Incorrect API key provided: ${given || '(none)'}. Find your key at the provider console.`, code: 'invalid_api_key' } });
    if (url.pathname === '/redirect/v1/models') { res.writeHead(302, { Location: 'http://127.0.0.1:1/elsewhere' }); return res.end(); }

    if (req.method === 'GET' && path === '/v1/models') return json(200, { object: 'list', data: [{ id: 'mock-gpt' }, { id: 'mock-gpt-mini' }, { id: 'mock-local' }] });
    if (req.method === 'GET' && path === '/v1beta/models') return json(200, { models: [{ name: 'models/mock-gemini', supportedGenerationMethods: ['generateContent'] }, { name: 'models/mock-embed', supportedGenerationMethods: ['embedContent'] }] });

    /* ---------------- OpenAI chat completions ---------------- */
    if (req.method === 'POST' && path === '/v1/chat/completions') {
      const msgs = body?.messages || [];
      if (!body?.stream) return json(200, { choices: [{ message: { role: 'assistant', content: 'pong' }, finish_reason: 'stop' }] });
      const lastUser = msgs.map((m) => m.role).lastIndexOf('user');
      const userText = typeof msgs[lastUser]?.content === 'string' ? msgs[lastUser].content : (msgs[lastUser]?.content || []).map((p) => p.text || '').join('');
      // Nudges from the loop are user messages too; the script marker is in the last one that has it.
      const scriptAt = msgs.findLastIndex((m) => m.role === 'user' && marker(typeof m.content === 'string' ? m.content : (m.content || []).map((p) => p.text || '').join('')));
      const name = scriptAt >= 0 ? marker(typeof msgs[scriptAt].content === 'string' ? msgs[scriptAt].content : msgs[scriptAt].content.map((p) => p.text || '').join('')) : 'hello';
      const step = msgs.slice(scriptAt + 1).filter((m) => m.role === 'assistant').length;
      entry.script = name; entry.step = step; entry.userText = userText;
      const act = (SCRIPTS[name] || SCRIPTS.hello)(step, { repo: repoOf(msgs[0]?.content) }) || { text: 'Script finished.' };
      if (act.status) return json(act.status, { error: { message: act.error, type: 'error' } });
      res.writeHead(200, { 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-cache' });
      const chunk = (delta, finish = null) => res.write(`data: ${JSON.stringify({ id: `chatcmpl-${n}`, object: 'chat.completion.chunk', model: body.model, choices: [{ index: 0, delta, finish_reason: finish }] })}\n\n`);
      chunk({ role: 'assistant', content: '' });
      if (act.slow) { for (let i = 0; i < 600 && !res.destroyed; i++) { chunk({ content: `word${i} ` }); await sleep(50); } return res.end(); }
      for (const piece of (act.text || '').match(/\S+\s*|\s+/g) || []) { chunk({ content: piece }); await sleep(2); }
      for (const [i, c] of (act.calls || []).entries()) {
        const args = c.rawArgs ?? JSON.stringify(c.args);
        const cut = Math.ceil(args.length / 2);
        chunk({ tool_calls: [{ index: i, id: `call_${n}_${i}`, type: 'function', function: { name: c.name, arguments: '' } }] });
        chunk({ tool_calls: [{ index: i, function: { arguments: args.slice(0, cut) } }] });
        chunk({ tool_calls: [{ index: i, function: { arguments: args.slice(cut) } }] });
      }
      chunk({}, act.calls?.length ? 'tool_calls' : 'stop');
      res.write('data: [DONE]\n\n');
      return res.end();
    }

    /* ---------------- Gemini streamGenerateContent ---------------- */
    const gm = /^\/v1beta\/models\/([^:]+):streamGenerateContent$/.exec(path);
    if (req.method === 'POST' && gm) {
      const contents = body?.contents || [];
      const textOf = (c) => (c.parts || []).map((p) => p.text || '').join('');
      const scriptAt = contents.findLastIndex((c) => c.role === 'user' && marker(textOf(c)));
      const name = scriptAt >= 0 ? marker(textOf(contents[scriptAt])) : 'hello';
      const after = contents.slice(scriptAt + 1);
      const step = after.filter((c) => c.role === 'model').length;
      entry.script = name; entry.step = step;
      // Function-call parts must come back with the signature they were issued with.
      entry.signaturesEchoed = after.filter((c) => c.role === 'model').flatMap((c) => c.parts).filter((p) => p.functionCall).every((p) => /^sig-/.test(p.thoughtSignature || ''));
      const act = (SCRIPTS[name] || SCRIPTS.hello)(step, { repo: repoOf(body?.systemInstruction?.parts?.[0]?.text) }) || { text: 'Script finished.' };
      if (act.status) return json(act.status, { error: { code: act.status, message: act.error, status: 'ERROR' } });
      res.writeHead(200, { 'Content-Type': 'text/event-stream' });
      const emit = (parts, finishReason) => res.write(`data: ${JSON.stringify({ candidates: [{ content: { role: 'model', parts }, ...(finishReason ? { finishReason } : {}), index: 0 }] })}\r\n\r\n`);
      if (act.slow) { for (let i = 0; i < 600 && !res.destroyed; i++) { emit([{ text: `word${i} ` }]); await sleep(50); } return res.end(); }
      for (const piece of (act.text || '').match(/(\S+\s*){1,3}|\s+/g) || []) { emit([{ text: piece }]); await sleep(2); }
      const bad = (act.calls || []).some((c) => c.rawArgs);
      if (bad) { emit([], 'MALFORMED_FUNCTION_CALL'); return res.end(); }
      for (const [i, c] of (act.calls || []).entries()) emit([{ functionCall: { name: c.name, args: c.args }, thoughtSignature: `sig-${n}-${i}` }]);
      emit([], 'STOP');
      return res.end();
    }
    json(404, { error: { message: `mock: no route ${req.method} ${path}` } });
  });
  return new Promise((resolve) => server.listen(port, '127.0.0.1', () => {
    const p = server.address().port;
    resolve({ port: p, origin: `http://127.0.0.1:${p}`, log, close: () => new Promise((r) => { server.closeAllConnections?.(); server.close(r); }) });
  }));
}
